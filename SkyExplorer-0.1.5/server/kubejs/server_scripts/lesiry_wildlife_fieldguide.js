PlayerEvents.loggedIn(event => {
  const server = event.server;
  const uuid = event.player.getUUID();
  server.scheduleInTicks(40, () => {
    const player = server.getPlayerList().getPlayer(uuid);
    if (player == null) return;
    if (typeof FieldGuide === 'undefined') {
      console.warn('[Lesiry Wildlife] Field Guide KubeJS binding unavailable; historical discoveries were not synced.');
      return;
    }
    lesiryWildlifeEntries.forEach(row => {
      if (FieldGuide.isUnlocked(player, row.entry)) {
        server.runCommandSilent('advancement grant ' + player.getGameProfile().getName() + ' only ' + row.advancement);
      }
    });
  });
});
